"""Public fields follow the team PDF; AgentContext is AI-internal checkpoint data."""

from typing import Any, Literal, NotRequired, Self, TypedDict

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator


class ContractModel(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True)

    @field_validator("*", mode="after")
    @classmethod
    def no_blank_strings(cls, value: Any) -> Any:
        if isinstance(value, str) and not value.strip():
            raise ValueError("Use null for unavailable optional values, not blank strings")
        return value


class Evidence(ContractModel):
    source: Literal["HISTORY", "SDR", "AMM"]
    ref_id: str
    excerpt: str = Field(min_length=1, max_length=300)
    why: str


class Classification(ContractModel):
    ata_chapter: str = Field(pattern=r"^[0-9]{2}$")
    linked_history_ids: list[str]
    sufficient: bool
    proposed_department: str | None
    rationale: str

    @model_validator(mode="after")
    def conditional_fields(self) -> Self:
        if self.sufficient and self.proposed_department is None:
            raise ValueError("sufficient=True requires proposed_department")
        return self


class Investigation(ContractModel):
    ata_chapter: str = Field(pattern=r"^[0-9]{2}$")
    finding: str
    severity: Literal["LOW", "MEDIUM", "HIGH", "AOG"]
    evidence: list[Evidence] = Field(min_length=1)
    proposed_department: str
    rationale: str


class Review(ContractModel):
    decision: Literal["PASS", "SUPPLEMENT", "HUMAN"]
    department: str | None
    comments: str
    supplement_request: str | None

    @model_validator(mode="after")
    def conditional_fields(self) -> Self:
        if self.decision == "PASS" and self.department is None:
            raise ValueError("PASS requires department")
        if self.decision == "SUPPLEMENT" and self.supplement_request is None:
            raise ValueError("SUPPLEMENT requires supplement_request")
        return self


class InternalHold(ContractModel):
    reason: Literal[
        "INSUFFICIENT_EVIDENCE",
        "INSUFFICIENT_INFORMATION",
        "DEPARTMENT_UNAVAILABLE",
        "TOOL_LIMIT",
        "VALIDATION_FAILED",
        "RETRY_LIMIT",
        "NEEDS_INPUT",
        "CONTEXT_CHANGED",
        "SNAPSHOT_CHANGED",
        "REQUEST_STOPPED",
        "UNSUPPORTED_EVIDENCE_SOURCE",
    ]
    summary: str
    unresolved_questions: list[str] = Field(default_factory=list)


class RetrievedRecord(ContractModel):
    """Recorded by the tool runner, not generated by an LLM."""

    source: Literal["HISTORY", "SDR", "AMM", "TECHNICAL_DOC"]
    ref_id: str
    content: str
    metadata: dict[str, Any] = Field(default_factory=dict)


class ToolTrace(ContractModel):
    tool: str
    question: str
    arguments: dict[str, Any]
    outcome: Literal["OK", "EMPTY", "NEEDS_INPUT", "ERROR"]
    attempts: int
    item_ids: list[str] = Field(default_factory=list)
    error_code: str | None = None
    response: dict[str, Any] = Field(default_factory=dict)
    started_at: str | None = None
    finished_at: str | None = None


class AgentContext(ContractModel):
    request_id: str
    records: list[RetrievedRecord] = Field(default_factory=list)
    departments: list[dict[str, Any]] = Field(default_factory=list)
    traces: list[ToolTrace] = Field(default_factory=list)
    hold: InternalHold | None = None
    context_version: int | None = None
    request_context: dict[str, Any] = Field(default_factory=dict)
    applied_scope: dict[str, Any] = Field(default_factory=dict)
    snapshots: dict[str, list[str]] = Field(default_factory=dict)
    cursors: dict[str, dict[str, Any]] = Field(default_factory=dict)
    jasc_candidates: list[dict[str, Any]] = Field(default_factory=list)
    final_evidence: list[Evidence] = Field(default_factory=list)
    final_validation: Literal["PENDING", "PASS", "HUMAN"] = "PENDING"
    prepared_payload: dict[str, Any] = Field(default_factory=dict)
    context_refresh_count: int = 0
    superseded_assessments: list[dict[str, Any]] = Field(default_factory=list)
    validated_at: str | None = None


class InvestigationAssessment(ContractModel):
    """Internal envelope only; Spring still receives Investigation alone."""

    investigation: Investigation
    technical_basis_ids: list[str] = Field(
        description="최종 판단에 필수로 사용한 기술자료 ID. 단순 조사 참고는 제외. 없으면 빈 목록."
    )


class ReviewAssessment(ContractModel):
    """Review's additional basis must survive final validation and handoff."""

    review: Review
    additional_evidence: list[Evidence] = Field(
        description="검토 결론에 사용한 추가 HISTORY/SDR/AMM 근거와 원문 인용. 없으면 빈 목록."
    )
    technical_basis_ids: list[str] = Field(
        description="검토 결론에 필수로 사용한 기술자료 ID. 없으면 빈 목록."
    )


class GraphState(TypedDict):
    request_id: str
    tail_number: str
    aircraft_model: str
    airline_code: str
    symptom_text: str
    classification: Classification | None
    investigations: list[Investigation]
    reviews: list[Review]
    retry_count: int
    # Private AI data; never included in Classification/Investigation/Review callbacks.
    agent_context: NotRequired[dict[str, Any]]


class NextStep(ContractModel):
    """Internal tool selection. Does not change the team's MCP input schemas."""

    action: Literal["CALL", "FINISH", "HOLD"]
    question: str = Field(description="이 호출로 확인할 판단 조건 또는 종료·보류 이유")
    tool_name: str | None
    arguments_json: str | None = Field(description="도구 인자 JSON 객체 문자열. 미사용 시 null")
    hold_reason: Literal["INSUFFICIENT_EVIDENCE", "INSUFFICIENT_INFORMATION"] | None

    @model_validator(mode="after")
    def conditional_fields(self) -> Self:
        if self.action == "CALL" and (self.tool_name is None or self.arguments_json is None):
            raise ValueError("CALL requires tool_name and arguments_json")
        if self.action == "HOLD" and self.hold_reason is None:
            raise ValueError("HOLD requires hold_reason")
        return self
